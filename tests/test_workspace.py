import json
from pathlib import Path

import pytest

from localpdf.backends import stand_in_backends
from localpdf.bench.schema import Dataset
from localpdf.bench.synthetic import build_dataset
from localpdf.security import UploadRejected
from localpdf.workspace import WorkspaceManager
from conftest import pages

ROOT = Path(__file__).resolve().parents[1]


@pytest.fixture
def mgr(tmp_path):
    return WorkspaceManager(tmp_path, stand_in_backends())


def test_workspaces_are_isolated(mgr):
    a, b = mgr.create("alice"), mgr.create("bob")
    a.kb.ingest_pages("secret.pdf", pages("Alice's private salary figure is 123456 dollars per year."))
    b.kb.ingest_pages("other.pdf", pages("Bob keeps bees and sells honey at the weekend market."))
    ans_b = b.pipeline.ask("What is the salary figure?")
    assert ans_b.abstained and "123456" not in ans_b.answer
    assert [d["filename"] for d in b.kb.list_documents()] == ["other.pdf"]
    assert "123456" in a.pipeline.ask("What is the private salary figure?").answer


def test_delete_workspace_removes_everything(mgr, tmp_path):
    w = mgr.create("temp1")
    w.kb.ingest_pages("x.pdf", pages("Some confidential text about turbines and generators."))
    d = w.dir
    assert d.exists()
    assert mgr.delete("temp1") and not d.exists() and not mgr.exists("temp1")
    assert not mgr.delete("temp1")
    with pytest.raises(KeyError):
        mgr.get("temp1")


def test_workspace_survives_restart(tmp_path):
    m1 = WorkspaceManager(tmp_path, stand_in_backends())
    m1.create("persist").kb.ingest_pages("p.pdf", pages("The reactor coolant temperature limit is 320 degrees."))
    m1.get("persist").close()
    m2 = WorkspaceManager(tmp_path, stand_in_backends())
    assert "320" in m2.get("persist").pipeline.ask("What is the coolant temperature limit?").answer


@pytest.mark.parametrize("bad", ["../etc", "a/b", "..", "", "a b", "x" * 80, "ws;rm"])
def test_path_traversal_ids_rejected(mgr, bad):
    with pytest.raises(UploadRejected):
        mgr.create(bad)
    assert not mgr.exists(bad)


def test_shipped_dataset_file_matches_generator():
    """datasets/synthetic_v1.jsonl is generated by scripts/make_synthetic_pdfs.py; it must not drift from the code."""
    f = ROOT / "datasets" / "synthetic_v1.jsonl"
    if not f.exists():
        pytest.skip("run scripts/make_synthetic_pdfs.py first")
    assert Dataset.load(f).sha256() == build_dataset().sha256()
