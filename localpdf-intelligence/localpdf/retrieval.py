"""Hybrid retrieval: dense + BM25 -> RRF fusion (over one or several query variants) -> dedupe -> rerank -> parent expand.

Every stage is switchable through RAGConfig, which is what lets the benchmark ablate and compare configurations.
"""
from __future__ import annotations

import re
from dataclasses import dataclass, field

import numpy as np

from .backends.base import Embedder, Reranker
from .config import RAGConfig
from .store import Filter, KnowledgeBase
from .util import content_tokens


@dataclass
class Hit:
    chunk_id: int
    doc_id: int
    filename: str
    page: int
    text: str                 # the matched child chunk (precise evidence; used for highlighting and citation checks)
    context: str              # what the LLM reads: the parent passage if parent_expand, else the child
    score: float              # reranker probability (or RRF-normalised score when rerank is off)
    rrf: float = 0.0
    parent_id: int = 0
    norm_hash: str = ""


def expand_queries(q: str, extra: list[str] | None = None) -> list[str]:
    """Deterministic query variants for multi-query retrieval: the question, a keyword-only form, and any
    LLM-provided rewrites. (LLM rewrites are generated by the pipeline, not here, so this stays testable.)"""
    kw = " ".join(content_tokens(q)[:12])
    out = [q]
    if kw and kw.lower() != q.lower():
        out.append(kw)
    for e in extra or []:
        if e and e.lower() not in {x.lower() for x in out}:
            out.append(e)
    return out[:4]


class Retriever:
    def __init__(self, kb: KnowledgeBase, embedder: Embedder, reranker: Reranker, cfg: RAGConfig):
        self.kb, self.embedder, self.reranker, self.cfg = kb, embedder, reranker, cfg

    def retrieve(self, query: str, flt: Filter | None = None, variants: list[str] | None = None,
                 top_k: int | None = None) -> list[Hit]:
        cfg, kb = self.cfg, self.kb
        top_k = top_k or cfg.top_k
        queries = expand_queries(query, variants) if cfg.multi_query else [query]
        allowed = kb.allowed_ids(flt)
        if allowed is not None and not allowed:
            return []

        rrf: dict[int, float] = {}
        for q in queries:
            lists = []
            if cfg.use_dense:
                qv = self.embedder.embed([q], is_query=True)[0]
                lists.append([i for i, _ in kb.dense(qv, cfg.dense_k, allowed)])
            if cfg.use_bm25:
                lists.append([i for i, _ in kb.bm25(q, cfg.bm25_k, flt)])
            for lst in lists:
                for rank, cid in enumerate(lst):
                    rrf[cid] = rrf.get(cid, 0.0) + 1.0 / (cfg.rrf_k + rank)
        if not rrf:
            return []

        pool_ids = sorted(rrf, key=rrf.get, reverse=True)[: max(cfg.dense_k, cfg.bm25_k)]
        rows = kb.get_chunks(pool_ids)
        # duplicate chunk suppression across documents (same normalised text): keep the best-fused copy
        seen: set[str] = set()
        cand = []
        for cid in pool_ids:
            r = rows.get(cid)
            if r is None or r["norm_hash"] in seen:
                continue
            seen.add(r["norm_hash"])
            cand.append(r)

        if cfg.rerank:
            probs = np.asarray(self.reranker.score(query, [r["text"] for r in cand]), dtype=float)
        else:  # no cross-encoder: report RRF mass scaled to [0,1] so downstream thresholds still mean something
            top = max(rrf[r["id"]] for r in cand) or 1.0
            probs = np.asarray([rrf[r["id"]] / top for r in cand])
        order = np.argsort(-probs)

        hits, used_parents = [], set()
        for j in order:
            r = cand[int(j)]
            if cfg.parent_expand and r["parent_id"] in used_parents:
                continue  # several children of one parent would repeat the same context
            used_parents.add(r["parent_id"])
            hits.append(Hit(chunk_id=r["id"], doc_id=r["doc_id"], filename=r["filename"], page=r["page"], text=r["text"],
                            context=r["parent_text"] if cfg.parent_expand else r["text"], score=float(probs[int(j)]),
                            rrf=rrf[r["id"]], parent_id=r["parent_id"], norm_hash=r["norm_hash"]))
            if len(hits) >= top_k:
                break
        return hits

    def retrieve_balanced(self, query: str, doc_ids: list[int], per_doc: int | None = None) -> list[Hit]:
        """Comparison questions: retrieve from each document separately and interleave, so one document cannot
        crowd the others out of the context window."""
        per_doc = per_doc or max(2, self.cfg.top_k // max(1, len(doc_ids)))
        per = {d: self.retrieve(query, Filter(doc_ids=[d]), top_k=per_doc) for d in doc_ids}
        per = {d: h for d, h in per.items() if h}
        if not per:
            return []
        best = max(h[0].score for h in per.values())
        keep = {d: h for d, h in per.items() if h[0].score >= 0.5 * best}
        order = sorted(keep, key=lambda d: -keep[d][0].score)
        out = []
        for i in range(per_doc):
            for d in order:
                if i < len(keep[d]):
                    out.append(keep[d][i])
        return out
